import assert from 'node:assert/strict';
import {cp,mkdir,readFile,rm,writeFile} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const output=resolve(root,'dist');
const base=(process.env.PAGES_BASE??'/trayn-nutrition-prototypes').replace(/\/$/,'');
assert.ok(base===''||/^\/[a-zA-Z0-9_/-]+$/.test(base),'Invalid Pages base path');
await rm(output,{recursive:true,force:true});await mkdir(output,{recursive:true});
for(const version of ['v1','v2','v3','v4'])await cp(resolve(root,version,'dist'),resolve(output,version),{recursive:true});
const chooser=(await readFile(resolve(root,'index.html'),'utf8')).replaceAll('/trayn-nutrition-prototypes/',`${base}/`);
await writeFile(resolve(output,'index.html'),chooser);await writeFile(resolve(output,'404.html'),chooser);await writeFile(resolve(output,'.nojekyll'),'');
console.log(`Assembled V1–V4 and opening studies for ${base||'/'} in ${output}`);
